#!/bin/bash
# types.sh — Single source of truth for TileOPs commit/PR/issue type conventions.
#
# Usage:
#   source scripts/ci/types.sh
#   # Now use $COMMIT_MSG_PATTERN, $BRANCH_NAME_PATTERN, TYPE_TO_LABEL, etc.
#
# This file is sourced by validation scripts and CI workflows.
# Update HERE first, then all consumers pick up the change automatically.

# ---------------------------------------------------------------------------
# Commit / PR types
# ---------------------------------------------------------------------------

COMMIT_PR_TYPES="Bench|BugFix|Chore|CI|Design|Doc|Enhancement|Feat|Fix|Maintain|Perf|Refactor|Style|Test"

# How the change was produced: foundry = kernel generated by the tilefoundry tool
ORIGIN_TAGS="foundry"

# Full commit message / PR title regex
#   [Type] description   or   [Type][Origin]?[Scope]? description
# Origin precedes scope so the slot stays decidable from position alone.
COMMIT_MSG_PATTERN="^\[(${COMMIT_PR_TYPES})\](\[(${ORIGIN_TAGS})\])?(\[[a-zA-Z0-9_-]+\])? .+"

# ---------------------------------------------------------------------------
# Branch naming
# ---------------------------------------------------------------------------

BRANCH_PREFIXES="bench|chore|design|doc|feat|fix|maintain|perf|refactor|style|test"
BRANCH_NAME_PATTERN="^(${BRANCH_PREFIXES})/[a-z0-9._-]+/[a-z0-9._-]+$"

# ---------------------------------------------------------------------------
# Type → GitHub label mapping
# ---------------------------------------------------------------------------

declare -A TYPE_TO_LABEL=(
  [Bench]=type:bench
  [BugFix]=type:fix
  [Chore]=type:chore
  [CI]=type:ci
  [Design]=type:design
  [Doc]=type:docs
  [Enhancement]=type:enhancement
  [Feat]=type:feat
  [Fix]=type:fix
  [Maintain]=type:maintain
  [Perf]=type:perf
  [Refactor]=type:refactor
  [Style]=type:style
  [Test]=type:test
)

# All type-related labels (used for stale-label cleanup)
ALL_TYPE_LABELS="type:bench type:bug type:chore type:ci type:design type:docs type:enhancement type:feat type:fix type:maintain type:perf type:refactor type:style type:test"

# ---------------------------------------------------------------------------
# Origin → GitHub label mapping
# ---------------------------------------------------------------------------

declare -A ORIGIN_TO_LABEL=(
  [foundry]=origin:foundry
)

# Separate from ALL_TYPE_LABELS so stale-type cleanup cannot strip these.
ALL_ORIGIN_LABELS="origin:foundry"

# ---------------------------------------------------------------------------
# Issue types (ALL CAPS, used in issue titles)
# ---------------------------------------------------------------------------

ISSUE_TYPES="BENCHMARK|BUG|DESIGN|DOCS|FEAT|MAINTAIN|META|PERF|REFACTOR|STYLE|TEST"

# Issue type → GitHub label (for auto-label workflow)
declare -A ISSUE_TYPE_TO_LABEL=(
  [BENCHMARK]=type:bench
  [BUG]=type:bug
  [DESIGN]=type:design
  [DOCS]=type:docs
  [FEAT]=type:feat
  [MAINTAIN]=type:maintain
  [META]=type:chore
  [PERF]=type:perf
  [REFACTOR]=type:refactor
  [STYLE]=type:style
  [TEST]=type:test
)

# Issue type → commit/PR type prefix
declare -A ISSUE_TO_COMMIT_TYPE=(
  [BENCHMARK]=Bench
  [BUG]=BugFix
  [DESIGN]=Design
  [DOCS]=Doc
  [FEAT]=Feat
  [MAINTAIN]=Maintain
  [META]=Chore
  [PERF]=Enhancement
  [REFACTOR]=Refactor
  [STYLE]=Style
  [TEST]=Test
)

# Issue type → branch prefix
declare -A ISSUE_TO_BRANCH_PREFIX=(
  [BENCHMARK]=bench
  [BUG]=fix
  [DESIGN]=design
  [DOCS]=doc
  [FEAT]=feat
  [MAINTAIN]=maintain
  [META]=chore
  [PERF]=perf
  [REFACTOR]=refactor
  [STYLE]=style
  [TEST]=test
)

# Default for unrecognized issue types
ISSUE_DEFAULT_COMMIT_TYPE="Fix"
ISSUE_DEFAULT_BRANCH_PREFIX="fix"
