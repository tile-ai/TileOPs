@dataclasses.dataclass(frozen=True)
class HadamardTransformCall(CallSpec):
    """Row length, base order and dtype; the batch is dynamic in every kernel."""

    n: int = 0
    base_order: int = 1
    dtype: torch.dtype = torch.bfloat16


class HadamardTransformFwdInterface(KernelInterface):
    """The scaled Hadamard transform of a tensor's last axis."""

    request = HadamardTransformCall

    @abstractmethod
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Transform each row of length ``call.n``; nothing is written in place.

        With ``m = call.n // call.base_order``, a row read as ``base_order`` segments of ``m``
        becomes ``x @ kron(B, H_m) / sqrt(n)``: ``H_m`` is the Sylvester Hadamard matrix of
        order ``m`` and ``B`` is ``HADAMARD_BASES[base_order]``, or ``[[1]]`` for base order 1.
        The products accumulate in float32 and round once to ``call.dtype``.

        Args:
            x: The input, ``(..., call.n)`` in ``call.dtype`` on ``call.device``, contiguous.

        Returns:
            A new contiguous tensor on ``call.device``, shaped and typed as *x*.
        """
